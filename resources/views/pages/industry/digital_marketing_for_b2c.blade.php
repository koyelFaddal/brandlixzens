                    <p>SEO works by improving various aspects of a website to make it more appealing to
                        search engines. This includes using relevant keywords, creating high-quality content,
                        and ensuring the site is technically sound.</p>
                </div>
            </div>
            <div class="faq-item">
                <div class="faq-question">
                    <p>Why is SEO important for businesses?</p>
                    <span class="toggle-btn">+</span>
                </div>
                <div class="faq-answer">
                    <p>SEO is important for businesses because it increases their online visibility, drives
                        organic traffic, and helps attract potential customers. It also builds brand credibility
                        and can lead to higher conversion rates.</p>
                </div>
            </div>
            <div class="faq-item">
                <div class="faq-question">
                    <p>What are the main types of SEO?</p>
                    <span class="toggle-btn">+</span>
                </div>
                <div class="faq-answer">
                    <p>The main types of SEO are on-page SEO, off-page SEO, and technical SEO. On-page
                        focuses on content and HTML source code, off-page involves external factors like
                        backlinks, and technical SEO ensures the website meets search engine requirements.</p>
                </div>
            </div>
            <div class="faq-item">
                <div class="faq-question">
                    <p>How do you perform keyword research for SEO?</p>
                    <span class="toggle-btn">+</span>
                </div>
                <div class="faq-answer">
                    <p>Keyword research for SEO involves identifying relevant keywords that potential
                        customers use in search engines. This can be done using tools like Google Keyword
                        Planner, Ahrefs, and SEMrush to find keywords with high search volume and low
                        competition.</p>
                </div>
            </div>
            <div class="faq-item">
                <div class="faq-question">
                    <p>What are backlinks and why are they important for SEO?</p>
                    <span class="toggle-btn">+</span>
                </div>
                <div class="faq-answer">
                    <p>Backlinks are links from other websites to your site. They are important for SEO
                        because they signal to search engines that your content is valuable and authoritative,
                        helping to improve your rankings.</p>
                </div>
            </div>
            <div class="faq-item">
                <div class="faq-question">
                    <p>How does mobile optimisation impact SEO?</p>
                    <span class="toggle-btn">+</span>
                </div>
                <div class="faq-answer">
                    <p>Mobile optimisation impacts SEO by ensuring that your website is accessible and
                        user-friendly on mobile devices. Google prioritises mobile-friendly sites in its
                        rankings, making it essential for SEO success.</p>
                </div>
            </div>
            <div class="faq-item">
                <div class="faq-question">
                    <p>What is the impact of page speed on SEO?</p>
                    <span class="toggle-btn">+</span>
                </div>
                <div class="faq-answer">
                    <p>Page speed impacts SEO by affecting user experience. Faster-loading pages are
                        favoured by search engines and users, leading to lower bounce rates and higher
                        rankings in search results.</p>
