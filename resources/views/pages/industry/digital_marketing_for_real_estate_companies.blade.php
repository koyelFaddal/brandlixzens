    // If not on Android (or WhatsApp not available), fallback to WhatsApp Web
    var webUrl = 'https://web.whatsapp.com/send?phone=' + phoneNumber + '&text=' + message;
    
    // Open WhatsApp Web in a new tab
    window.open(webUrl, '_blank');
  }
}

