                        dropdownContent.style.display = isVisible ? 'none' : 'block';
                        dropdownIcon.classList.toggle('fa-caret-down', isVisible);
                        dropdownIcon.classList.toggle('fa-caret-up', !isVisible);
                    });
                });
            })
